// Writes web-rust's src/presets.rs from web-react's own code: the six presets on the
// instrument pads with what the screen shows of them and what the engine is
// sent. Run from web-react after changing a preset or a patch:
//   npx tsx scripts/export-presets.tsx && (cd ../web-rust && cargo fmt)
import { writeFileSync } from "node:fs";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import {
  DEVICE_PRESETS,
  KNOB_STEPS,
  engineName,
  keyPiece,
  presetValues,
  type DevicePreset,
} from "../app/components/home/deviceEngine";
import { F3_MIDI, clampOctave } from "../app/components/home/deviceMath";
import { DRUM_PIECES } from "../app/components/home/instrumentIcons";
import type { KitId } from "../app/lib/physical";
import { PATCH_BY_ID } from "../app/lib/physical/patches";
import {
  formatParam,
  stepToValue,
  valueToStep,
} from "../app/lib/physical/patches/format";
import { moduleLabel, paramModules } from "../app/lib/physical/patches/params";
import type { ParamSpec, Patch } from "../app/lib/physical/patches/types";

// As SoundProvider orders and names the params the knobs pick.
const moduleOrder = ({ params, family }: Patch) =>
  paramModules(params, family).flatMap((module) => module.specs);
const stepsOf = (spec: ParamSpec) => spec.options?.length ?? KNOB_STEPS;
const paramName = (
  { family }: Patch,
  specs: readonly ParamSpec[],
  spec: ParamSpec,
) =>
  specs.some((other) => other !== spec && other.label === spec.label)
    ? `${moduleLabel(family, spec.section)} ${spec.label}`
    : spec.label;

const KEYS = 24;
const string = (text: string) =>
  text.includes('"') ? `r#"${text}"#` : JSON.stringify(text);
const float = (x: number) => (Number.isInteger(x) ? x.toFixed(1) : String(x));

const pads = Array.from({ length: 6 }, (_, pad) =>
  DEVICE_PRESETS.find((preset) => preset.pad === pad)!,
);

function preset(preset: DevicePreset) {
  const patch = PATCH_BY_ID[preset.target];
  const own = presetValues(preset);
  const specs = moduleOrder(patch);
  const params = specs.map((spec) => {
    const steps = stepsOf(spec);
    const step = valueToStep(spec, own[spec.id], steps);
    // Turning back to the preset's own step restores its exact value.
    const sends = Array.from({ length: steps }, (_, s) =>
      s === step ? own[spec.id] : stepToValue(spec, s, steps),
    );
    return `Param {
      name: ${string(paramName(patch, specs, spec))},
      id: ${string(spec.id)},
      step: ${step},
      values: &[${sends.map((value) => string(formatParam(spec, value))).join(", ")}],
      sends: &[${sends.map(float).join(", ")}],
    }`;
  });
  const others = patch.params
    .filter((spec) => !specs.includes(spec))
    .map((spec) => `(${string(spec.id)}, ${float(own[spec.id])})`);
  let pieces = "None";
  if (patch.family === "drums") {
    const keys = Array.from({ length: KEYS }, (_, semitone) => {
      const id = keyPiece(preset.target as KitId, F3_MIDI + semitone);
      const { name, Icon } = DRUM_PIECES[id];
      // Without lucide's own class and aria-hidden: the key hides its face.
      const face = Icon
        ? renderToStaticMarkup(createElement(Icon)).replace(
            / class="lucide[^"]*" aria-hidden="true"/,
            "",
          )
        : name;
      return `Piece { name: ${string(name)}, id: ${string(id)}, face: ${string(face)} }`;
    });
    pieces = `Some(&[${keys.join(",\n")}])`;
  }
  return `Preset {
    name: ${string(preset.name)},
    engine: ${string(engineName(preset.target))},
    target: ${string(preset.target)},
    octave: ${preset.octave},
    octaves: (${clampOctave(-99, preset)}, ${clampOctave(99, preset)}),
    params: &[${params.join(",\n")}],
    others: &[${others.join(", ")}],
    pieces: ${pieces},
  }`;
}

const out = `//! The six presets on the instrument pads, as web-react ships them: the
//! name, how the sound is made, the instrument it plays and its octave and
//! reach, every parameter the knobs pick and set with the display of each
//! step and the value it sends, and for a kit the piece on each key.
//!
//! Generated by \`scripts/export-presets.tsx\`; don't edit by hand.

// Values as web-react computes them, a resonance's 1/√2 among them.
#![allow(clippy::approx_constant)]

pub struct Param {
  pub name: &'static str,
  /// The engine's id for it.
  pub id: &'static str,
  /// The step it starts on.
  pub step: usize,
  /// The display of each knob step.
  pub values: &'static [&'static str],
  /// The value each knob step sends: the preset's own at its own step.
  pub sends: &'static [f64],
}

pub struct Piece {
  pub name: &'static str,
  /// The engine's id for it.
  pub id: &'static str,
  /// An icon's SVG markup, or the bol's name.
  pub face: &'static str,
}

pub struct Preset {
  pub name: &'static str,
  /// How the sound is made: the model's exciter.
  pub engine: &'static str,
  /// The engine's instrument or kit.
  pub target: &'static str,
  /// Semitones added to keybed notes, so the instrument plays in its
  /// register.
  pub octave: i32,
  /// The lowest and highest octave shift the arrows reach: the keybed may
  /// hang at most 11 notes past either end of the instrument's range. A kit
  /// plays pieces by key, so it never shifts.
  pub octaves: (i8, i8),
  pub params: &'static [Param],
  /// The instrument's params the knobs don't pick, with the preset's values.
  pub others: &'static [(&'static str, f64)],
  /// A kit's pieces, by keybed semitone.
  pub pieces: Option<&'static [Piece; ${KEYS}]>,
}

pub const PRESETS: [Preset; ${pads.length}] = [${pads.map(preset).join(",\n")}];
`;
writeFileSync(new URL("../../web-rust/src/presets.rs", import.meta.url), out);
console.log(`wrote ${pads.length} presets`);
